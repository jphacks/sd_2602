import { URL } from 'node:url';
import process from 'node:process';
// Base44 bundles each function separately. Keep deployable copies in sync.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const read = p => readFileSync(new URL(p, root), 'utf8');
const save = (p, value) => {
  if (process.argv.includes('--check')) {
    if (read(p) !== value) throw new Error('LINE_BUNDLE_OUTDATED: '+p);
  } else writeFileSync(new URL(p, root), value);
};
save('base44/functions/line-card-demo/presentation.js', read('base44/functions/line-webhook/presentation.js'));
let transport = read('base44/functions/line-webhook/handler.js');
transport = transport.replace('import { buildDemoMessages, DEMO_VERSION, DEMO_SNAPSHOT } from "./cards.js";\n', '').replace('import { demoImageResponse } from "./image.js";\n', '').replace('import { commandFor, commandReply }', 'import { commandFor }');
const start = transport.indexOf('export function replyFor');
const end = transport.indexOf('export async function verifySignature');
transport = transport.slice(0, start) + transport.slice(end);
transport = transport.replace('resolveMessages = replyFor', 'resolveMessages = () => []').replace('imageResponse = demoImageResponse', 'imageResponse = () => null').replace('snapshotInfo = () => ({ fixture_version: DEMO_VERSION, candidate_count: DEMO_SNAPSHOT.candidates.length })', 'snapshotInfo = () => ({})');
save('base44/functions/line-card-demo/transport.js', '// Generated by scripts/package-line-functions.mjs; edit line-webhook/handler.js.\n'+transport);
